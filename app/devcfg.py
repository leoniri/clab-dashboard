def _pick_yaml(text):
    """A ruamel round-trip YAML whose indentation reproduces this file best."""
    from ruamel.yaml import YAML
    best, best_score = None, None
    for mapping, seq, offset in ((2, 4, 2), (2, 2, 0), (4, 4, 2), (2, 4, 0), (4, 6, 4)):
        y = YAML()
        y.preserve_quotes = True
        y.width = 4096
        y.indent(mapping=mapping, sequence=seq, offset=offset)
        try:
            doc = y.load(text)
            buf = io.StringIO()
            y.dump(doc, buf)
        except Exception:                               # noqa: BLE001
            continue
        a, b = text.splitlines(), buf.getvalue().splitlines()
        score = sum(1 for x, z in zip(a, b) if x != z) + abs(len(a) - len(b))
        if best_score is None or score < best_score:
            best, best_score = y, score
        if score == 0:
            break
    if best is None:
        raise DevError("the topology file could not be parsed for a round-trip edit")
    return best


def _set_node_startup(lab, node, rel):
    """Add startup-config: rel to the node in the topology, comments preserved."""
    with open(lab["path"]) as fh:
        text = fh.read()
    y = _pick_yaml(text)
    doc = y.load(text)
    nodes = doc["topology"]["nodes"]
    if nodes.get(node) is None:
        nodes[node] = {}
    nodes[node]["startup-config"] = rel
    buf = io.StringIO()
    y.dump(doc, buf)
    new = buf.getvalue()
    return editor.write_file(lab, os.path.basename(lab["path"]), new, editor.sha(text))


def _add_node_bind(lab, node, rel, target):
    """Add a `rel:target` bind to the node in the topology, comments preserved."""
    with open(lab["path"]) as fh:
        text = fh.read()
    y = _pick_yaml(text)
    doc = y.load(text)
    nodes = doc["topology"]["nodes"]
    if nodes.get(node) is None:
        nodes[node] = {}
    binds = nodes[node].get("binds")
    if binds is None:
        nodes[node]["binds"] = binds = []
    binds.append("%s:%s" % (rel, target))
    buf = io.StringIO()
    y.dump(doc, buf)
    return editor.write_file(lab, os.path.basename(lab["path"]), buf.getvalue(), editor.sha(text))


def _frr_conf_rel(lab, node):
    """(path of the file bind-mounted as /etc/frr/frr.conf, whether to add the bind)."""
    doc = _topo_doc(lab)
    ncfg, kcfg, defaults, _ = _node_cfg(doc, node)
    base = os.path.dirname(lab["path"])
    for src in (ncfg, kcfg, defaults):
        for b in src.get("binds") or []:
            host, _, rest = str(b).partition(":")
            if rest.split(":")[0] == "/etc/frr/frr.conf" and editor._inside(base, host):
                return os.path.normpath(host), False
    return os.path.join("configs", "%s.frr.conf" % node), True


def _startup_rel(lab, node, platform=None):
    """(relative path to write, whether the topology must be pointed at it)."""
    if platform == "frr":
        return _frr_conf_rel(lab, node)
    doc = _topo_doc(lab)
    ncfg, kcfg, defaults, _ = _node_cfg(doc, node)
    sc = ncfg.get("startup-config")
    base = os.path.dirname(lab["path"])
    if isinstance(sc, str) and "\n" not in sc and not sc.startswith("/") \
            and "{{" not in sc and "__clab" not in sc:
        full = os.path.normpath(os.path.join(base, sc))
        if full.startswith(os.path.realpath(base) + os.sep) or full.startswith(base + os.sep):
            return os.path.normpath(sc), False
    # no per-node file (or inline / templated / outside the lab dir): give the
    # node its own file
    return os.path.join("configs", "%s.%s" % (node, "cli" if platform == "srl" else "cfg")), True


def save_startup(lab, node, audit=None):
    """Write the node's cleaned running-config into its startup-config file.

    lab is a lab dict from the collector (needs path, name, nodes, containers).
    Returns {"node", "path", "created", "topology_updated", "saved_version", "bytes"}.
    """
    _, nent, c, platform = resolve({lab["id"]: lab}, lab["id"], node)
    conn = _connect(lab, node, c, platform)
    try:
        raw = _fetch_running(conn)
    finally:
        conn.disconnect()
    text = _clean(platform, raw, lab, node)
    if len(text.splitlines()) < 3 or ("hostname" not in text and platform != "srl"):
        raise DevError("the running-config from %s looks truncated - not saved" % node, 502)

    rel, repoint = _startup_rel(lab, node, platform)
    full = os.path.join(os.path.dirname(lab["path"]), rel)
    exists = os.path.isfile(full)
    res = {"node": node, "path": rel, "created": not exists, "topology_updated": False,
           "bytes": len(text)}
    # file first, so the topology never points at something missing
    w = editor.write_file(lab, rel, text, None, create=not exists)
    if repoint and platform == "frr":
        _add_node_bind(lab, node, rel, "/etc/frr/frr.conf")
        res["topology_updated"] = True
        res["note"] = "the topology now bind-mounts %s; it takes effect at the next deploy" % rel
    elif repoint:
        _set_node_startup(lab, node, rel)
        res["topology_updated"] = True
    res["saved_version"] = (w or {}).get("saved_version")
    if audit:
        audit("DEVICE-SAVE lab=%s node=%s file=%s bytes=%d previous-kept=%s"
              % (lab.get("name"), node, rel, len(text), res["saved_version"]))
    return res


