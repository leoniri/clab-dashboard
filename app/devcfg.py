def _topo_doc(lab):
    with open(lab["path"]) as fh:
        return yaml.safe_load(fh) or {}


def _node_cfg(doc, node):
    topo = doc.get("topology") or {}
    nodes = topo.get("nodes") or {}
    ncfg = nodes.get(node) if isinstance(nodes, dict) else None
    ncfg = ncfg if isinstance(ncfg, dict) else {}
    defaults = topo.get("defaults") if isinstance(topo.get("defaults"), dict) else {}
    kind = ncfg.get("kind") or defaults.get("kind")
    kinds = topo.get("kinds") if isinstance(topo.get("kinds"), dict) else {}
    kcfg = kinds.get(kind) if isinstance(kinds.get(kind), dict) else {}
    return ncfg, kcfg, defaults, kind


def credentials(lab, node):
    """USERNAME / PASSWORD from the topology (node > kind > defaults), as term.py does."""
    user, pw = DEFAULT_USER, DEFAULT_PASS
    try:
        doc = _topo_doc(lab)
    except Exception:                                   # noqa: BLE001
        return user, pw
    ncfg, kcfg, defaults, kind = _node_cfg(doc, node)
    user, pw = KIND_LOGINS.get(kind, (user, pw))
    env = {}
    for src in (defaults.get("env"), kcfg.get("env"), ncfg.get("env")):
        if isinstance(src, dict):
            env.update(src)
    # native container NOSes ignore USERNAME / PASSWORD - their login is fixed
    native = kind in ("nokia_srlinux", "srl", "arista_ceos", "ceos", "juniper_crpd", "crpd")
    if env.get("USERNAME") and not native:
        user = str(env["USERNAME"])
    if env.get("PASSWORD") and not native:
        pw = str(env["PASSWORD"])
    # What the router was really given wins: containerlab hands vrnetlab its
    # credentials as --username/--password, and for some kinds (n9kv: always
    # admin/admin) it ignores the topology's USERNAME/PASSWORD.
    args = _container_args(lab, node)
    if args.get("username") and args.get("password"):
        user, pw = args["username"], args["password"]
    return user, pw


def _container_args(lab, node):
    import json as _json
    import subprocess
    name = next((c.get("name") for c in lab.get("containers") or [] if c.get("short") == node), None)
    if not name:
        return {}
    try:
        out = subprocess.run([DOCKER, "inspect", "-f", "{{json .Config.Cmd}}", name],
                             capture_output=True, text=True, timeout=15).stdout
        cmd = _json.loads(out or "null") or []
    except Exception:                                   # noqa: BLE001
        return {}
    res = {}
    for i, a in enumerate(cmd[:-1]):
        if a in ("--username", "--password"):
            res[a[2:]] = cmd[i + 1]
    return res


def resolve(lab_index, lab_id, node):
    """(lab, node entry, container, platform) for a running, supported node."""
    lab = lab_index.get(lab_id)
    if lab is None:
        raise DevError("unknown lab id", 404)
    if not isinstance(node, str) or not NODE_RE.match(node):
        raise DevError("bad node name")
    nent = next((n for n in lab.get("nodes") or [] if n.get("name") == node), None)
    if nent is None:
        raise DevError("%s is not a node of %s" % (node, lab.get("name")), 404)
    platform = platform_of(nent.get("kind"), nent.get("image"))
    if not platform:
        raise DevError("%s is %s - device configuration is available for IOS-XE "
                       "(c8000v, csr1000v), IOS-XR (XRd), NX-OS (n9kv), FRR and SR Linux "
                       "nodes" % (node, nent.get("kind")))
    c = next((c for c in lab.get("containers") or [] if c.get("short") == node), None)
    if not c or c.get("state") != "running" or not (c.get("ipv4") or platform in EXEC_PLATFORMS):
        raise DevError("%s is not running - start the lab first" % node, 409)
    return lab, nent, c, platform


# vtysh prints these on every call when /etc/frr/vtysh.conf does not exist
_VTYSH_NOISE = re.compile(r"^(% Can't open configuration file /etc/frr/vtysh\.conf.*|"
                          r"Configuration file\[/etc/frr/frr\.conf\] processing failure: 11)$")


class ExecConn:
    """The two calls devcfg makes on a netmiko connection, over docker exec."""

    def __init__(self, container, platform):
        self.container, self.platform = container, platform

    def exec(self, argv, stdin=None, timeout=60):
        import subprocess
        try:
            p = subprocess.run([DOCKER, "exec", "-i", self.container] + argv,
                               input=stdin, capture_output=True, text=True, timeout=timeout)
        except Exception as exc:                        # noqa: BLE001
            raise DevError("%s: %s" % (self.container, exc), 502)
        out = "\n".join(l for l in (p.stdout + p.stderr).splitlines() if not _VTYSH_NOISE.match(l))
        return p.returncode, out

    def send_command(self, cmd, read_timeout=60, **_):
        if self.platform == "frr":
            return self.exec(["vtysh", "-c", cmd], timeout=read_timeout)[1]
        return self.exec(["sr_cli", "-d", cmd], timeout=read_timeout)[1]

    def disconnect(self):
        pass


def _connect(lab, node, container, platform, timeout=60):
    if platform in EXEC_PLATFORMS:
        return ExecConn(container["name"], platform)
    from netmiko import ConnectHandler
    user, pw = credentials(lab, node)
    try:
        return ConnectHandler(
            device_type=platform, host=container["ipv4"], username=user, password=pw,
            conn_timeout=20, auth_timeout=30, banner_timeout=30, read_timeout_override=None,
            fast_cli=False, global_delay_factor=1, session_timeout=timeout,
        )
    except Exception as exc:                            # noqa: BLE001
        raise DevError("could not log in to %s (%s): %s - it may still be booting"
                       % (node, container["ipv4"], str(exc).splitlines()[0][:200]), 502)


