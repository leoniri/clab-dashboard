def _err(exc):
    status = getattr(exc, "status", 400)
    return status, {"error": str(exc)}


def handle_get(path, q, lab_index):
    """GET routes. Returns (status, body), or None when the path is not ours."""
    if path != "/api/device/running":
        return None
    try:
        return 200, running_config(lab_index, q.get("lab", ""), q.get("node", ""))
    except (DevError, editor.EditError) as exc:
        return _err(exc)


def _post_config(payload, lab_index, audit):
    try:
        return 200, push_config(lab_index, payload.get("lab_id"), payload.get("node"),
                                payload.get("config"), bool(payload.get("save_startup")),
                                audit=audit)
    except (DevError, editor.EditError) as exc:
        return _err(exc)


def _post_save(payload, lab_index, audit):
    try:
        lab = lab_index.get(payload.get("lab_id"))
        if lab is None:
            raise DevError("unknown lab id", 404)
        return 200, save_startup(lab, payload.get("node"), audit=audit)
    except (DevError, editor.EditError) as exc:
        return _err(exc)


POST_ROUTES = {
    "/api/device/config": _post_config,
    "/api/device/save-startup": _post_save,
}
