def _fetch_running(conn):
    if isinstance(conn, ExecConn) and conn.platform == "srl":
        return conn.send_command("info flat", read_timeout=90)
    return conn.send_command("show running-config", read_timeout=90)


# Top-level IOS-XE blocks the saved startup-config must not carry, each with
# its indented children. The first group is what vrnetlab's bootstrap owns
# (management VRF + GigabitEthernet1 - saving them would pin the old
# management addressing, because the startup file is applied after the
# bootstrap); the crypto pki blocks are the self-signed and SLA certificates,
# which the box regenerates and whose hex dumps do not re-apply.
XE_DROP_BLOCKS = [
    r"^interface GigabitEthernet ?1$",
    r"^vrf definition clab-mgmt$",
    r"^crypto pki (trustpoint|certificate chain) ",
]
XE_DROP_LINES = [
    r"^Building configuration",
    r"^Current configuration",
    r"^! Last configuration change",
    r"^! NVRAM config last updated",
    r"^license (udi|boot level|smart)",
    r"^ip route vrf clab-mgmt ",
    r"^ipv6 route vrf clab-mgmt ",
    # netconf/restconf are switched on by the bootstrap; re-applying
    # "netconf detailed-error" from the ISO is rejected (CVAC PRC_INVALID)
    r"^netconf (detailed-error|max-sessions)",
    r"^netconf-yang$",
    r"^restconf$",
    # a platform default IOS-XE writes itself and rejects when re-applied
    r"^platform sslvpn use-pd",
]


def _drop(text, blocks, lines_re):
    out, skipping = [], False
    for line in text.replace("\r", "").split("\n"):
        if skipping:
            if line.startswith((" ", "\t")) or line.strip() == "quit":
                continue
            skipping = False
        if any(re.match(p, line) for p in blocks):
            skipping = True
            continue
        if any(re.match(p, line) for p in lines_re):
            continue
        out.append(line)
    # collapse the runs of top-level "!" that removed blocks leave behind;
    # indented "!" lines are left alone - in XR sub-modes they close a block
    res = []
    for line in out:
        if line.rstrip() == "!" and res and res[-1].rstrip() == "!":
            continue
        res.append(line)
    while res and res[0].strip() in ("", "!"):  # noqa: E501 (leading separators)
        res.pop(0)
    txt = "\n".join(res).rstrip() + "\n"
    if not txt.rstrip().endswith("end"):
        txt += "end\n"
    return txt


def _explicit_no_shut(text):
    """`show running-config` omits "no shutdown" on an interface that is up
    (it is the displayed default), but these routers boot their data
    interfaces shut. Add it to every interface block that is not shut, so a
    saved config brings the links back up after a redeploy."""
    out, block = [], None
    lines = text.split("\n")

    def close():
        if block is not None and not block["shut"]:
            out.insert(block["end"], " no shutdown")

    for line in lines:
        if line.startswith("interface "):
            close()
            out.append(line)
            block = {"end": len(out), "shut": False}
            continue
        if block is not None:
            if line.startswith(" "):
                if line.strip() == "shutdown":
                    block["shut"] = True
                out.append(line)
                block["end"] = len(out)
                continue
            close()
            block = None
        out.append(line)
    close()
    return "\n".join(out)


def clean_xe(text, user=DEFAULT_USER):
    """IOS-XE running-config -> startup-config for the vrnetlab c8000v launcher."""
    return _explicit_no_shut(_drop(text, XE_DROP_BLOCKS,
                                   XE_DROP_LINES + [r"^username %s " % re.escape(user)]))


# IOS-XR: the launcher's first-boot bootstrap owns the clab user and MgmtEth.
XR_DROP_BLOCKS = [r"^interface MgmtEth0/RP0/CPU0/0$"]
XR_DROP_LINES = [
    r"^!! ",
    r"^[A-Z][a-z]{2} [A-Z][a-z]{2} +\d+ \d\d:\d\d:\d\d",   # "Sat Sep 19 16:54:09.449 UTC"
    r"^Building configuration",
]


def clean_xr(text, user=DEFAULT_USER):
    """IOS-XR running-config -> first-boot config for the vrnetlab XRd launcher."""
    return _explicit_no_shut(_drop(text, XR_DROP_BLOCKS + [r"^username %s$" % re.escape(user)],
                                   XR_DROP_LINES))


# NX-OS: the n9kv launcher's bootstrap owns hostname-adjacent housekeeping, the
# users, VRF management and mgmt0; it feeds our file line by line in config mode
# (so no "end"). Running-config already shows "no shutdown" explicitly.
NXOS_DROP_BLOCKS = [r"^vdc ", r"^vrf context management$", r"^interface mgmt0$"]
NXOS_DROP_LINES = [
    r"^!Command:", r"^!Running configuration", r"^!Time:", r"^!NVRAM config",
    r"^version ", r"^snmp-server user ", r"^boot nxos ",
    r"^ssh key ", r"^ip route 0\.0\.0\.0/0 .* vrf management",
]


def clean_nxos(text, user=DEFAULT_USER):
    # only the launcher's own login user is dropped (it recreates it); other
    # users - e.g. the lab's clab user - are kept, hashed passwords re-apply
    out = _drop(text, NXOS_DROP_BLOCKS,
                NXOS_DROP_LINES + [r"^username (%s|admin) " % re.escape(user)])
    lines = out.rstrip("\n").split("\n")
    if lines and lines[-1].strip() == "end":
        lines.pop()
    return "\n".join(l for l in lines) .rstrip() + "\n"


def clean_frr(text):
    """vtysh `show running-config` -> frr.conf (no banner, no trailing end)."""
    lines = [l for l in text.replace("\r", "").split("\n")
             if not re.match(r"^(Building configuration|Current configuration)", l)]
    while lines and lines[0].strip() in ("", "!"):
        lines.pop(0)
    while lines and lines[-1].strip() in ("", "end"):
        lines.pop()
    return "\n".join(lines).rstrip() + "\n"


# What containerlab's SR Linux bootstrap owns (management, TLS, gNMI/JSON-RPC,
# AAA users, the factory CPM filters): saving it would pin old certificates and
# keys and fight the next deploy. Everything else is kept.
SRL_DROP = re.compile(r"^set / (system (tls|grpc-server|json-rpc-server|aaa|ssh-server|"
                      r"management|snmp|netconf-server|gnmi-server|banner|dns|lldp|"
                      r"logging|information|name|dns-instance|control-plane-traffic|ndk-server)|"
                      r"network-instance mgmt|interface mgmt0|acl|"
                      r"tools|platform|bfd$)(\s|$)")


def clean_srl(text):
    """`info flat` -> a .cli startup file clab applies after boot."""
    out = [l for l in text.replace("\r", "").split("\n")
           if l.startswith("set / ") and not SRL_DROP.match(l)
           and not re.match(r"^set /\s+!", l)]          # "!!! ..." annotations
    return "\n".join(out) + "\n"


def _clean(platform, raw, lab, node):
    if platform == "frr":
        return clean_frr(raw)
    if platform == "srl":
        return clean_srl(raw)
    user, _ = credentials(lab, node)
    if platform == "cisco_nxos":
        return clean_nxos(raw, user)
    return clean_xe(raw, user) if platform == "cisco_xe" else clean_xr(raw, user)


def running_config(lab_index, lab_id, node):
    lab, nent, c, platform = resolve(lab_index, lab_id, node)
    conn = _connect(lab, node, c, platform)
    try:
        raw = _fetch_running(conn)
    finally:
        conn.disconnect()
    text = _clean(platform, raw, lab, node)
    return {"node": node, "platform": PLATFORM_NAMES[platform], "text": text}


