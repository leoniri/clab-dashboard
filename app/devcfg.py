#!/usr/bin/env python3
"""
Configuration of running routers: show running-config, push config, and save
the running config back into the node's startup-config file.

Why "save to startup" matters: containerlab can only apply topology changes to
vrnetlab routers by redeploying, and a redeploy boots every VM from its
startup-config. Saving the running config first is what makes a redeploy keep
whatever was configured on the box.

Supported kinds are the ones the dashboard has templates for. The vrnetlab
ones run a VM inside the container, reached over SSH on its management
address; FRR and SR Linux are native containers, driven with docker exec:

    cisco_c8000v, cisco_csr1000v   netmiko cisco_xe
    cisco_xrd_vrouter              netmiko cisco_xr
    cisco_n9kv                     netmiko cisco_nxos
    linux + an FRR image           docker exec vtysh    (frr.conf is bind-mounted)
    nokia_srlinux                  docker exec sr_cli   (startup is a .cli file)

The client names a lab id and a node name; the container, address, platform
and credentials are all resolved here from the server's own lab index and the
topology file. Credentials never leave the server.

Startup-config cleaning (what the vrnetlab launchers accept at first boot):

  IOS-XE  the launcher writes its bootstrap (hostname, clab user, clab-mgmt VRF,
          Gi1, netconf) and appends our file into a config ISO that IOS applies
          line by line, AFTER the bootstrap. From `show running-config` we drop
          the banner lines (Building / Current configuration, Last configuration
          change), what the bootstrap owns (vrf definition clab-mgmt, interface
          GigabitEthernet1, the clab-mgmt default routes, the clab username -
          otherwise stale management addressing or an old password would win),
          the crypto pki trustpoint + certificate-chain blocks (self-signed and
          SLA certs are regenerated by the box; their hex dumps do not re-apply),
          the license udi/boot lines and the netconf/restconf lines the bootstrap
          already sets ("netconf detailed-error" is rejected when re-applied). Every interface that is not shut gets
          an explicit "no shutdown" (running-config omits it; data ports boot
          shut).
  IOS-XR  the launcher prepends its bootstrap and loads the whole file as XR
          first-boot config (no commit needed). We drop the timestamp line and
          the "!! ..." header, the MgmtEth0/RP0/CPU0/0 block and the clab
          username block (the bootstrap owns both), add "no shutdown" to every
          interface that is not shut, and make sure the file ends with "end".
"""

