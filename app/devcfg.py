def _config_lines(config):
    if not isinstance(config, str) or not config.strip():
        raise DevError("no configuration to push")
    if len(config.encode()) > MAX_CONFIG_BYTES:
        raise DevError("configuration too large (limit 256 KB)")
    lines = []
    for line in config.replace("\r", "").split("\n"):
        s = line.rstrip()
        if not s.strip():
            continue
        # these are handled here; letting the user send them would leave the
        # session in the wrong mode
        if s.strip().lower() in ("configure terminal", "conf t", "configure", "end", "commit",
                                 "exit config", "abort", "commit now", "enter candidate",
                                 "enter candidate private"):
            continue
        lines.append(s)
    if not lines:
        raise DevError("nothing left to push after removing configure/end/commit")
    return lines


FRR_ERR = re.compile(r"^line \d+: %.*$", re.M)


def push_frr(conn, lines):
    """vtysh -f applies a config file line by line; a bad line is reported per
    daemon as "line N: % ..." and the others are applied."""
    rc, out = conn.exec(["sh", "-c", "cat > /tmp/clabd-push.conf && vtysh -f /tmp/clabd-push.conf; "
                         "rc=$?; rm -f /tmp/clabd-push.conf; exit $rc"],
                        stdin="\n".join(lines) + "\n", timeout=120)
    errors = sorted(set(m.group(0).strip() for m in FRR_ERR.finditer(out)))
    if rc != 0 and not errors:
        errors = [l for l in out.splitlines() if "failure" in l][:5] or ["vtysh exited with %d" % rc]
    return out, errors


def push_srl(conn, lines):
    """SR Linux: the lines go into a private candidate that is committed only if
    every line parsed - a bad line aborts the whole change."""
    bad = [l for l in lines if not re.match(r"^\s*(set|delete) ", l)]
    if bad:
        return "", ["SR Linux takes flat `set / ...` / `delete / ...` lines here; not: %s" % bad[0][:120]]
    rc, out = conn.exec(["sr_cli", "-ed", "--post", "commit now"], stdin="\n".join(lines) + "\n",
                        timeout=120)
    errors = [l.strip() for l in out.splitlines() if re.search(r"(Parsing error|Error|error:)", l)]
    if rc != 0 and not errors:
        errors = ["sr_cli exited with %d" % rc]
    if errors:
        out += "\n--- rejected: nothing was committed ---\n"
    return out, errors


def push_nxos(conn, lines):
    """NX-OS also applies line by line; errors are "% Invalid command" / "ERROR:"."""
    out = conn.send_config_set(lines, read_timeout=120, cmd_verify=True)
    errors = [m.group(0).strip() for m in NXOS_ERR.finditer(out)]
    return out, errors


def push_xe(conn, lines):
    """IOS-XE applies line by line - there is no transaction to roll back. With
    cmd_verify on, netmiko waits for each echo, so the "% Invalid input"
    that IOS prints a moment later lands in the output."""
    out = conn.send_config_set(lines, read_timeout=120, cmd_verify=True)
    errors = [m.group(0).strip() for m in XE_ERR.finditer(out)]
    return out, errors


_XR_INCONSISTENT = "inconsistent with persistent configuration"
_XR_COMMIT_FAIL = re.compile(r"Failed to commit|% ?Failed|commit.*(rejected|failed)|"
                             + _XR_INCONSISTENT, re.I)


def _xr_pending(conn):
    """Uncommitted lines in the current XR config session, if any."""
    show = conn.send_command_timing("show configuration", read_timeout=60)
    body = [l for l in show.splitlines()
            if l.strip() and not l.startswith(("!!", "Building")) and l.strip() not in ("end", "!")
            and not re.match(r"^[A-Z][a-z]{2} [A-Z][a-z]{2} +\d+ ", l) and "#" not in l]
    return body


def _xr_abort(conn):
    return conn.send_command_timing("abort", read_timeout=30)


def push_xr(conn, lines):
    """Enter config, apply, commit - or abort, so nothing is ever half applied.

    A freshly booted XRd refuses every commit until `clear configuration
    inconsistency` has been run; we detect that on entering config mode, run
    it, and say so in the output."""
    out = conn.config_mode()
    if _XR_INCONSISTENT in out:
        out += "\n" + _xr_abort(conn)
        out += "\n--- XR reports running vs persistent configuration inconsistent " \
               "(normal after first boot): running 'clear configuration inconsistency' ---\n"
        out += conn.send_command_timing("clear configuration inconsistency", read_timeout=180,
                                        last_read=4)
        out += "\n" + conn.config_mode()
    out += conn.send_config_set(lines, enter_config_mode=False, exit_config_mode=False,
                                read_timeout=120, cmd_verify=True)
    errors = [m.group(0).strip() for m in XR_ERR.finditer(out)]
    if errors:
        out += "\n" + _xr_abort(conn)
        out += "\n--- rejected while typing: nothing was committed (session aborted) ---\n"
        return out, errors
    commit = conn.send_command_timing("commit", read_timeout=150, last_read=3)
    out += "\n" + commit
    pending = [] if _XR_COMMIT_FAIL.search(commit) else _xr_pending(conn)
    if _XR_COMMIT_FAIL.search(commit) or pending:
        failed = conn.send_command_timing("show configuration failed", read_timeout=60)
        out += "\n" + failed + "\n" + _xr_abort(conn)
        out += "\n--- commit failed: nothing was applied (session aborted) ---\n"
        # the useful part: "!!% <reason>" lines under each rejected command
        reasons = [l.strip().lstrip("!%").strip() for l in failed.splitlines()
                   if l.strip().startswith("!!%")]
        errors = ["commit failed"] + (reasons or [l.strip() for l in commit.splitlines()
                                                 if "Failed to commit" in l])[:20]
        return out, errors
    end = conn.send_command_timing("end", read_timeout=30)
    out += "\n" + end
    if "Uncommitted changes" in end:        # belt and braces: never leave a prompt open
        out += conn.send_command_timing("no", read_timeout=30)
        return out, ["changes were left uncommitted - discarded"]
    return out, []


def push_config(lab_index, lab_id, node, config, save_startup_after=False, audit=None):
    lab, nent, c, platform = resolve(lab_index, lab_id, node)
    lines = _config_lines(config)
    conn = _connect(lab, node, c, platform, timeout=150)
    t0 = time.time()
    try:
        if platform == "cisco_xe":
            out, errors = push_xe(conn, lines)
        elif platform == "frr":
            out, errors = push_frr(conn, lines)
        elif platform == "srl":
            out, errors = push_srl(conn, lines)
        elif platform == "cisco_nxos":
            out, errors = push_nxos(conn, lines)
        else:
            out, errors = push_xr(conn, lines)
    finally:
        try:
            conn.disconnect()
        except Exception:                               # noqa: BLE001
            pass
    ok = not errors
    res = {"node": node, "ok": ok, "errors": errors, "output": out.replace("\r", ""),
           "lines": len(lines), "seconds": round(time.time() - t0, 1),
           "platform": PLATFORM_NAMES[platform]}
    if platform in ("cisco_xe", "cisco_nxos", "frr") and errors:
        res["note"] = ("%s applies configuration line by line: the lines without an "
                       "error were applied." % PLATFORM_NAMES[platform])
    if audit:
        audit("DEVICE-CONFIG lab=%s node=%s lines=%d ok=%s"
              % (lab.get("name"), node, len(lines), ok))
    if save_startup_after and (ok or platform in ("cisco_xe", "cisco_nxos", "frr")):
        res["saved"] = save_startup(lab, node, audit=audit)
    return res


